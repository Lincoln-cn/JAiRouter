-- V18：控制台页面访问记录（B4，2026-11-18）
--
-- 需求：记录「谁看过哪一页」，并与权限管理页放在一起（用户决定，m10072）。
--
-- 为什么不复用 security_audit：
--   1) 语义不同。审计表回答「谁做了什么敏感操作」，浏览流水回答「谁在用哪个页面」；
--      混进去会让按事件类型统计审计的口径失真，也让审计页被浏览流水淹没。
--   2) security_audit.event_type 在库层是 ENUM，每新增一个事件类型都要在本目录写一段
--      「重设 enum 类型」的迁移（见 V7/V15/V16/V17）。浏览数据是高频、低价值、可丢弃的，
--      不该让它去承担那个约束的风险。
--
-- 粒度：只记 主体 + 路径 + 角色 + 时间。不记客户端 IP、不记查询参数。
create table if not exists ui_page_views (
    id bigint generated by default as identity primary key,
    user_id varchar(128) not null,
    path varchar(200) not null,
    role varchar(32),
    viewed_at timestamp not null
);

create index if not exists idx_ui_page_view_viewed_at on ui_page_views (viewed_at);

create index if not exists idx_ui_page_view_path on ui_page_views (path, viewed_at);
