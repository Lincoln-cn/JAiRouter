package org.unreal.modelrouter.persistence.migration;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.init.ScriptUtils;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * V21 迁移（{@code config_data} 去重 + 唯一约束）的落地验证（#1249）.
 *
 * <p>缺陷史：{@code saveConfig} 的「查 latest 不存在 → 插入」是 check-then-act，
 * 并发保存同一份配置会写下两行相同的 {@code (config_key, version)}；之后每次启动
 * {@code VersionSyncService} 都按 (key, version) 查单行，命中两行即抛
 * {@code NonUniqueResultException}，进程以退出码 1 结束，重启不自愈。</p>
 *
 * <p>V21 由此承担两件事：先清掉存量重复行（否则建约束会失败），再建唯一约束。
 * 本类在真实 H2 上执行脚本本身，断言去重结果与约束的检测力 ——
 * 光看「迁移脚本能跑过」不足以证明它删对了行。</p>
 */
@DisplayName("V21 config_data 去重与唯一约束")
class ConfigDataDedupMigrationTest {

    private static final String MIGRATION = "db/migration/h2/V21__config_data_unique_version.sql";

    private JdbcDataSource dataSource;
    private JdbcTemplate jdbc;

    @BeforeEach
    void setUp() {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:dedup-" + System.nanoTime()
                + ";DB_CLOSE_DELAY=-1;MODE=MySQL;DATABASE_TO_UPPER=FALSE");
        dataSource.setUser("sa");
        dataSource.setPassword("");
        jdbc = new JdbcTemplate(dataSource);

        jdbc.execute("""
                create table config_data (
                    is_latest boolean not null,
                    version integer not null,
                    created_at timestamp(6) not null,
                    id bigint generated by default as identity,
                    updated_at timestamp(6) not null,
                    config_key varchar(255) not null,
                    config_value TEXT not null,
                    primary key (id)
                )""");
    }

    private void runMigration() throws SQLException {
        try (Connection connection = dataSource.getConnection()) {
            ScriptUtils.executeSqlScript(connection, new ClassPathResource(MIGRATION));
        }
    }

    private void insert(final String key, final int version, final boolean latest) {
        jdbc.update("insert into config_data (is_latest, version, created_at, updated_at, config_key, config_value)"
                + " values (?, ?, current_timestamp, current_timestamp, ?, '{}')", latest, version, key);
    }

    private List<Integer> versionsOf(final String key) {
        return jdbc.queryForList(
                "select version from config_data where config_key = ? order by version", Integer.class, key);
    }

    private long latestCountOf(final String key) {
        Long count = jdbc.queryForObject(
                "select count(*) from config_data where config_key = ? and is_latest = true", Long.class, key);
        return count == null ? -1 : count;
    }

    @Test
    @DisplayName("同一 (key, version) 的重复行只保留最后写入的那一行")
    void keepsTheNewestDuplicateRow() throws SQLException {
        insert("cfg", 1, false);
        long firstId = jdbc.queryForObject("select max(id) from config_data", Long.class);
        insert("cfg", 1, true);
        insert("cfg", 2, false);
        insert("other", 1, true);

        runMigration();

        assertEquals(List.of(1, 2), versionsOf("cfg"), "重复的 version=1 只应剩一行");
        assertEquals(1, versionsOf("other").size(), "其它 key 不受影响");

        Long keptId = jdbc.queryForObject(
                "select id from config_data where config_key = 'cfg' and version = 1", Long.class);
        assertTrue(keptId != null && keptId > firstId, "保留的应是 id 更大的那一行（最后写入）");
    }

    @Test
    @DisplayName("去重后每个 key 恰好保留一行 is_latest=true")
    void rebuildsLatestFlag() throws SQLException {
        insert("cfg", 1, true);
        insert("cfg", 1, true);
        insert("cfg", 2, false);
        insert("other", 1, true);

        runMigration();

        assertEquals(1, latestCountOf("cfg"), "cfg 应恰有一行 is_latest=true");
        assertEquals(1, latestCountOf("other"));
        Integer latestVersion = jdbc.queryForObject(
                "select version from config_data where config_key = 'cfg' and is_latest = true", Integer.class);
        assertEquals(2, latestVersion, "is_latest 应指向最新版本");
    }

    @Test
    @DisplayName("约束建立后再写同一 (key, version) 会被数据库拒绝")
    void rejectsDuplicateInsertAfterMigration() throws SQLException {
        insert("cfg", 1, true);
        runMigration();

        assertThrows(Exception.class, () -> insert("cfg", 1, false),
                "(config_key, version) 唯一约束必须挡住重复写入");
        assertEquals(1, versionsOf("cfg").size());
    }

    @Test
    @DisplayName("空表上跑迁移不报错（新装环境）")
    void worksOnEmptyTable() throws SQLException {
        runMigration();
        insert("cfg", 1, true);
        assertEquals(1, versionsOf("cfg").size());
    }
}
